export function t(
  key: string,
  locale: Locale,
  vars?: Record<string, string | number>,
): string {
  let value =
    messages[locale]?.[key] ?? messages.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}
